# %% [markdown]
# # Per-configuration summary tables (position) — one row per pipeline variant
#
# The "inventory" view: for every pipeline configuration that has been trained
# (tail × window × smoothing), the mean across datasets of each dataset's
# per-fold median R² / MAE, per region, for all cohorts and for experts only.
#
# Two flavours of every metric: on each run's **own** test bins (runs that keep
# the tail include it, so R² is not comparable across rows) and restricted to
# bins with **true position ≤ 62.9 cm** (the fair cross-row comparison; runs
# with the history window lose ~2 padding bins per trial just before the cut).
#
# Outputs under `results/plots/effects-ladder/`: `config_summary_all.md`
# (all cohorts, per region) and `config_summary_experts.md` (experts only).

# %%
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent if "__file__" in dir() else Path.cwd().parent
sys.path.insert(0, str(ROOT))

from analysis.loaders import CM_PER_DEGREE, CONTEXT_END_CM  # noqa: E402
from analysis.metrics import error_summary  # noqa: E402
from analysis.results import discover_studies, fold_predictions, load_final_results  # noqa: E402

# %%
CONFIGS = [  # (label, tail, window, smoothing, results dir or None if never run)
    ("Baseline", "Sí", "Sí", "No", "results"),
    ("Sin cola", "No", "Sí", "No", "results_posend515"),
    ("Sin ventana", "Sí", "No", "No", "results_raw_w010"),
    ("Suavizado", "Sí", "Sí", "Sí", "results_smooth200_w212"),
    ("Sin ventana & Suavizado", "Sí", "No", "Sí", "results_smooth200_w010"),
    ("Sin cola & Sin ventana", "No", "No", "No", "results_notail_raw_w010"),
    ("Sin cola & Suavizado", "No", "Sí", "Sí", None),
    ("Sin cola & Sin ventana & Suavizado", "No", "No", "Sí", "results_notail_smooth_w010"),
]
REGIONS = [("Piriforme", "Pir"), ("CA3", "CA3"), ("DG", "DG")]
PLOT_DIR = ROOT / "results" / "plots" / "effects-ladder"
PLOT_DIR.mkdir(parents=True, exist_ok=True)


def dataset_metrics(results_dir, study):
    """Per-fold medians of R²/MAE on own support and on true ≤ 62.9 cm."""
    final = load_final_results(ROOT / results_dir, study)
    own, ctx = [], []
    for t, p in fold_predictions(final, "position"):
        t, p = t * CM_PER_DEGREE, p * CM_PER_DEGREE
        own.append(error_summary(t, p))
        ctx.append(error_summary(t, p, t <= CONTEXT_END_CM))
    return (np.median([o["r2"] for o in own]), np.median([o["mae"] for o in own]),
            np.median([c["r2"] for c in ctx]), np.median([c["mae"] for c in ctx]))


def fmt(x, nd):
    return "—" if x is None or pd.isna(x) else f"{x:.{nd}f}"


def region_table(region_key, experts_only):
    lines = ["| Experimento | Cola | Ventana | Suavizado | R² | MAE (cm) | R² ≤62.9 | MAE ≤62.9 "
             "| N | datasets |", "|---|---|---|---|---:|---:|---:|---:|---:|---|"]
    for label, tail, window, smooth, rd in CONFIGS:
        vals, names = [], []
        if rd is not None and (ROOT / rd).is_dir():
            for info in discover_studies(ROOT / rd, "pos"):
                if info.region != region_key or (experts_only and info.cohort != "expert"):
                    continue
                vals.append(dataset_metrics(rd, info.study))
                names.append(info.animal)
        v = np.array(vals) if vals else None
        cells = ([fmt(v[:, i].mean(), nd) for i, nd in ((0, 3), (1, 1), (2, 3), (3, 1))]
                 if v is not None else ["—"] * 4)
        lines.append(f"| {label} | {tail} | {window} | {smooth} | {' | '.join(cells)} "
                     f"| {len(vals)} | {', '.join(names) if names else '—'} |")
    return lines


def write(path, experts_only):
    title = "expert datasets only" if experts_only else "all cohorts"
    out = [f"# Per-configuration position summary — {title}", "",
           "Generated by `exploration/18-config-summary-tables.py`. R²/MAE = mean across datasets "
           "of each dataset's per-fold median (5 outer folds). 'R² / MAE' on each run's own test "
           "bins (tail runs include the tail → not comparable across rows); '≤62.9' evaluated only "
           "on bins with true position ≤ 62.9 cm — the fair cross-row comparison (window runs lose "
           "~2 padding bins per trial there).", ""]
    for name, key in REGIONS:
        out += [f"### {name}", ""] + region_table(key, experts_only) + [""]
    Path(path).write_text("\n".join(out) + "\n")
    print(f"📁 {Path(path).relative_to(ROOT)}")
    return out


all_lines = write(PLOT_DIR / "config_summary_all.md", experts_only=False)
exp_lines = write(PLOT_DIR / "config_summary_experts.md", experts_only=True)
print("\n".join(exp_lines))
